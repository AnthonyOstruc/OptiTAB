"""Vérification exacte (sympy) de tous les résultats de la notion 238 « Proportionnalité et pourcentages »."""
from sympy import Rational as R, symbols, Eq, solve, nsimplify

OK = 0


def q(s):
    return nsimplify(s, rational=True) if isinstance(s, str) else R(s)


def eg(a, b):
    global OK
    assert q(a) == q(b), (a, b)
    OK += 1


def vrai(c):
    global OK
    assert c
    OK += 1


