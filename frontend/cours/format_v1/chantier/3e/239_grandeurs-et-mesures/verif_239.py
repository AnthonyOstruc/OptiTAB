# -*- coding: utf-8 -*-
"""Vérification (sympy, valeurs exactes) des calculs de la notion 239 « Grandeurs et mesures »."""
from sympy import Rational as R, pi, nsimplify

n_ok = 0


def ok(cond, msg):
    global n_ok
    assert cond, msg
    n_ok += 1


def q(s):
    return nsimplify(s)


# ---- cours / fiche
ok(R(24, 10) * 60 - 2 * 60 == 24 and 1 + R(15, 60) == R(5, 4), "cours durées")
ok(pi * 3**2 * 5 / 3 == 15 * pi and abs(float(15 * pi) - 47.1) < 0.05, "cours cône")
ok(5 * R(1, 100) == R(5, 100) and 2 * R(1, 1000) == R(2, 1000), "cours maquette")
ok(72 / q("3.6") == 20 and 600 / 15 == 40 and q("2.5") * 360 == 900 and 2 * 3 == 6, "cours grandeurs")
ok(90 * 2 == 180, "cours graphique")
ok(q("0.42") * 10000 == 4200, "tableau aires")
# ---- 2254
ok(q("3.8") * 1000 == 3800 and q("0.42") * 10**4 == 4200 and R(6500, 10**4) == q("0.65") and q("0.03") * 10**6 == 30000, "2254")
# ---- 2255
ok(q("2.7") * 1000 == 2700 and R(450, 1000) == q("0.45") and q("3.5") * 1000 == 3500 and q("0.8") * 1000 == 800 and R(1600, 1000) > q("1.5"), "2255")
# ---- 2256
ok(q("0.75") * 60 == 45 and R(42, 60) == q("0.7") and q("0.2") * 60 == 12 and 3 + R(20, 60) == R(10, 3), "2256")
ok(1 + q("0.30") != q("1.5") and q("0.3") * 60 == 18, "2256 Q5")
# ---- 2257
ok(150 / q("2.5") == 60 and 60 * 4 == 240 and R(90, 60) == q("1.5") and abs(150 / 2.30 - 65.2) < 0.05, "2257")
# ---- 2258
ok(R(84, 7) == 12 and 12 * 25 == 300 and R(30, 12) == q("2.5") and 12 * 60 == 720, "2258")
# ---- 2259
Vp = 6 * 4 * q("2.5")
Vc = pi * 3**2 * 10
ok(Vp == 60 and Vc == 90 * pi and round(float(Vc)) == 283 and round(float(Vc) - 60) == 223, "2259")
# ---- 2260
ok(6 * 6 == 36 and R(36 * 10, 3) == 120 and 36 * 10 == 360, "2260 pyramide")
Vk = pi * 3**2 * 8 / 3
ok(Vk == 24 * pi and round(float(Vk), 1) == 75.4, "2260 cône")
# ---- 2261
ok(90 / q("3.6") == 25 and 12 * q("3.6") == q("43.2") and 108 / q("3.6") == 30 and 30 * q("3.6") == 108, "2261")
# ---- 2262
ok(54 / q("3.6") == 15 and 15 * q("0.8") == 12 and 90 / q("3.6") == 25 and 25 * q("0.8") == 20 and 54 * q("0.8") == q("43.2"), "2262")
# ---- 2263
ok(q("2.5") * 360 == 900 and 1000 / q("2.5") == 400 and 1500 / q("2.5") == 600 and R(540, 200) == q("2.7"), "2263")
# ---- 2264
ok(R(45, 60) == q("0.75") and q("1.2") * q("0.75") == q("0.9") and q("0.9") * q("0.24") == q("0.216"), "2264 a")
ok(q("1.2") * 90 == 108 and 108 * q("0.24") == q("25.92"), "2264 b")
# ---- 2265
ok(q("0.35") * 1000 == 350 and 350 * 60 == 21000 and 21000 * 4 == 84000 and 63 / q("0.35") == 180, "2265")
# ---- 2266 (sommets (0;0) (1;90) (1,5;90) (3;240))
ok(90 / 1 == 90 and (240 - 90) / q("1.5") == 100 and R(240, 3) == 80 and (90 + 100) / 2 == 95, "2266")
# ---- 2267
V = 60 * 30 * 40
ok(V == 72000 and 90 * 45 * 60 == 243000 and V * q("1.5")**3 == 243000, "2267 volumes")
ok(60 * 30 == 1800 and 90 * 45 == 4050 and R(4050, 1800) == q("1.5")**2 and 72 * q("1.5") == 108, "2267 aires")
# ---- 2268
ok(R(12, 18) == R(2, 3) and R(2, 3) * 60 == 40 and R(2, 3) + 1 == R(5, 3) and 24 / R(5, 3) == q("14.4"), "2268")
# ---- 2269
ok(R(1, 30) + R(1, 45) == R(1, 18) and R(540, 30) == 18 and R(540, 45) == 12 and R(540, 30) == 18, "2269")
# ---- 2270
ok(5 * q("2.6") - 2 == 11 and R(22, 8) == q("2.75") and q("2.75") / q("2.5") == q("1.1") and 5 - q("2.75") == q("2.25"), "2270")
# ---- 2271
ok(2 * q("0.05") == q("0.1") and 24 * 3600 == 86400 and q("0.1") * 86400 == 8640 and q("8.64") * 30 == q("259.2"), "2271 a")
ok(q("0.2592") * 4 == q("1.0368"), "2271 b")
# ---- 2272
Vg = 12 * q("1.5") * q("0.06")
ok(Vg == q("1.08") and q("1.6") * Vg == q("1.728") and q("1.728") / q("1.5") == q("1.152") and q("1.728") - q("1.5") == q("0.228"), "2272")
# ---- 2273
ok(8 * 4 * q("1.5") == 48 and 48000 / 20 == 2400 and 2400 / 60 == 40 and 48 * q("4.10") == q("196.8"), "2273")
ok(8 + 40 == 48, "2273 : lundi 8 h + 40 h = mercredi 0 h (48 h après lundi 0 h)")
# ---- 2274
Vv = pi * 4**2 * 12 / 3
ok(Vv == 64 * pi and round(float(Vv)) == 201 and round(float(Vv) / 10, 1) == 20.1, "2274 verre")
Vj = Vv * R(1, 2)**3
ok(Vj == 8 * pi and pi * 2**2 * 6 / 3 == 8 * pi and round(float(Vj)) == 25 and Vj / Vv == R(1, 8), "2274 jus")

print(f"verif_239 : {n_ok} contrôles, tout est juste.")
