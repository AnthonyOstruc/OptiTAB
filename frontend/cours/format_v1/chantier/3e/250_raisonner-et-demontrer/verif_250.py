# -*- coding: utf-8 -*-
"""Vérification (sympy) de tous les calculs et identités de la notion 250 « Raisonner et démontrer »."""
from fractions import Fraction as F
import math
import sympy as sp

x, n, a, b, k, m = sp.symbols("x n a b k m", integer=True)
X = sp.symbols("X")  # réel
OK = 0


def ok(cond, msg):
    global OK
    assert cond, msg
    OK += 1


def ident(e1, e2, msg):
    ok(sp.expand(e1 - e2) == 0, msg)


# ------------------------------------------------------------------ COURS
ok(0.5 ** 2 == 0.25 and 0.25 < 0.5, "cours contre-exemple carré")
ok(8 ** 2 != 5 ** 2 + 6 ** 2 and 5 ** 2 + 6 ** 2 == 61, "cours contraposée DEF 5,6,8")
ok(13 ** 2 == 5 ** 2 + 12 ** 2 == 169, "cours 5,12,13")
ident(n + (n + 1), 2 * n + 1, "cours consécutifs impair")
ident(5 * a + 5 * b, 5 * (a + b), "cours multiples de 5")
ok((3 + 4) * 3 + 4 == 25 and (-1 + 4) * (-1) + 4 == 1, "cours programme essais")
ident((X + 4) * X + 4, (X + 2) ** 2, "cours programme carré")
ident(n + (n + 1) + (n + 2), 3 * (n + 1), "fiche trois consécutifs")

# ------------------------------------------------------------------ 2485
ok(2 + 3 == 5 and sp.isprime(2) and sp.isprime(3), "2485 Q2")
ok(2 * -3 == -6 and -6 < -3, "2485 Q3")
ident(4 * k, 2 * (2 * k), "2485 Q4")
ok(2 * (1 + 9) == 20 and 4 * 5 == 20 and 1 * 9 == 9 and 5 * 5 == 25, "2485 Q5")

# ------------------------------------------------------------------ 2486
ok(14 == 2 * 7 and 15 == 2 * 7 + 1, "2486 Q1")
ident((2 * a + 1) + (2 * b + 1), 2 * (a + b + 1), "2486 Q2")
ok(7 + 5 == 12, "2486 figure 7+5")
ident(2 * a + (2 * b + 1), 2 * (a + b) + 1, "2486 Q3")
ident((2 * a + 1) * (2 * b + 1), 4 * a * b + 2 * a + 2 * b + 1, "2486 Q4 dev")
ident((2 * a + 1) * (2 * b + 1), 2 * (2 * a * b + a + b) + 1, "2486 Q4")
ident((2 * n) ** 2, 4 * n ** 2, "2486 Q5")

# ------------------------------------------------------------------ 2487
prog = lambda t: (t + 5) * 2 - 2 * t
for t in (3, -7, F(1, 2)):
    ok(prog(t) == 10, f"2487 essai {t}")
ok(3 + 5 == 8 and 16 - 6 == 10 and -7 + 5 == -2 and -4 - (-14) == 10 and F(11, 2) * 2 == 11, "2487 étapes")
ident(2 * (X + 5) - 2 * X, 10, "2487 Q5")

# ------------------------------------------------------------------ 2488
vals = [t * t + t + 41 for t in range(5)]
ok(vals == [41, 43, 47, 53, 61] and all(sp.isprime(v) for v in vals), "2488 Q1")
ok(61 % 7 == 5 and 61 // 7 == 8 and 11 * 11 == 121, "2488 Q1 61")
ok(all(sp.isprime(t * t + t + 41) for t in range(40)), "2488 vrai de 0 à 39")
ok(40 ** 2 + 40 + 41 == 1681 == 41 * 41, "2488 Q3")
ok(41 ** 2 + 41 + 41 == 41 * 43, "2488 Q5")

# ------------------------------------------------------------------ 2489
ok(360 - 3 * 90 == 90 and 180 - 45 - 45 == 90, "2489 Q3 Q4")

# ------------------------------------------------------------------ 2490
ident(6 * k, 3 * (2 * k), "2490 Q1")
ok(9 % 3 == 0 and 9 % 6 != 0, "2490 Q2")
ok((5 + 0) % 3 != 0 and 50 % 6 != 0, "2490 Q3")
ok(3 ** 2 == (-3) ** 2 == 9, "2490 Q5")

# ------------------------------------------------------------------ 2491
ok(3 ** 2 + 4 ** 2 == 25 and 6 ** 2 == 36, "2491 Q2 Q3")
ok(4 ** 2 - 3 ** 2 == 7 and round(math.sqrt(7), 1) == 2.6, "2491 Q4")

# ------------------------------------------------------------------ 2492
ok([t * (t + 1) for t in range(1, 6)] == [2, 6, 12, 20, 30], "2492 Q1")
ident((2 * k) * (2 * k + 1), 2 * (k * (2 * k + 1)), "2492 Q3")
ident((2 * k + 1) * (2 * k + 2), 2 * ((2 * k + 1) * (k + 1)), "2492 Q4")
ident(n * (n + 1), n ** 2 + n, "2492 Q5")

# ------------------------------------------------------------------ 2493
ok(4 + 5 + 6 == 15 and 10 + 11 + 12 == 33 and 99 + 100 + 101 == 300, "2493 Q1")
ident(n + (n + 1) + (n + 2), 3 * (n + 1), "2493 Q3")
ok(2025 / 3 == 675 and 674 + 675 + 676 == 2025 and 100 % 3 == 1, "2493 Q5")

# ------------------------------------------------------------------ 2494
ok((1 + 3) ** 2 == 16 and 1 + 9 == 10, "2494 Q1 contre-exemple")
ok(sp.expand((X + 3) ** 2 - (X ** 2 + 9)) != 0, "2494 Q1 fausse")
ident((X + 3) ** 2, X ** 2 + 6 * X + 9, "2494 Q1 vraie forme")
ident((X + 1) ** 2 - (X - 1) ** 2, 4 * X, "2494 Q2")
ident((X - 2) * (X + 2), X ** 2 - 4, "2494 Q3")
ok(2 * 1 ** 2 == 2 and (2 * 1) ** 2 == 4, "2494 Q4")
ident((X + 1) * (X + 2) - X * (X + 3), 2, "2494 Q5")

# ------------------------------------------------------------------ 2495
notes = [10, 10, 10, 18]
ok(sum(notes) == 48 and F(sum(notes), 4) == 12 and sum(v >= 12 for v in notes) == 1, "2495 Q1")
ok(sp.Rational(sorted(notes)[1] + sorted(notes)[2], 2) == 10, "2495 Q3")
notes5 = [4, 6, 12, 14, 14]
ok(sum(notes5) == 50 and sorted(notes5)[2] == 12, "2495 Q5")

# ------------------------------------------------------------------ 2496
AB, AC, BC = F(48, 10), F(64, 10), F(8)
ok(AB ** 2 == F(2304, 100) and AC ** 2 == F(4096, 100) and AB ** 2 + AC ** 2 == BC ** 2 == 64, "2496 Q2")
aire = AB * AC / 2
ok(AB * AC == F(3072, 100) and aire == F(1536, 100), "2496 Q4")
ok(2 * aire / BC == F(384, 100), "2496 Q5")

# ------------------------------------------------------------------ 2497
ok(F(3) / F(75, 10) == F(2, 5) == F(4, 10), "2497 Q1")
ok(F(2, 5) * 12 == F(48, 10), "2497 Q4")
ok(F(5, 10) == F(1, 2) != F(2, 5), "2497 Q5")

# ------------------------------------------------------------------ 2498
ok(10 ** 2 == 6 ** 2 + 8 ** 2 == 100, "2498 Q1")
ok(9 ** 2 == 81 and 5 ** 2 + 7 ** 2 == 74, "2498 Q5")

# ------------------------------------------------------------------ 2499
ident(4 * a * b / 2, 2 * a * b, "2499 Q2")
ident((a + b) ** 2 - 2 * a * b, a ** 2 + b ** 2, "2499 Q4")
ok((3 + 4) ** 2 == 49 and 2 * 3 * 4 == 24 and 49 - 24 == 25 == 3 ** 2 + 4 ** 2, "2499 Q5")

# ------------------------------------------------------------------ 2500
A = lambda t: (t + 3) ** 2 - 9
B = lambda t: (t + 6) * t
ok(A(2) == B(2) == 16 and A(-5) == B(-5) == -5, "2500 Q1 Q2")
ident((X + 3) ** 2 - 9, X ** 2 + 6 * X, "2500 A")
ident((X + 6) * X, X ** 2 + 6 * X, "2500 B")
ok(set(sp.solve(X * (X + 6), X)) == {0, -6}, "2500 Q4")
ok(sp.minimum((X + 3) ** 2 - 9, X) == -9, "2500 Q5 minimum")

# ------------------------------------------------------------------ 2501
Aire = X * (20 - X)
ident(Aire, 20 * X - X ** 2, "2501 Q2")
ident(100 - (X - 10) ** 2, Aire, "2501 Q3")
ok(sp.maximum(Aire, X, sp.Interval.open(0, 20)) == 100 and sp.solve(sp.diff(Aire, X), X) == [10], "2501 Q4")
ok(Aire.subs(X, 7) == 91 == 100 - (7 - 10) ** 2, "2501 Q5")

# ------------------------------------------------------------------ 2502
ok((180 - 36) / 2 == 72 and 72 / 2 == 36 and 180 - 36 - 72 == 72, "2502 angles")
bc = 2 * 5 * math.sin(math.radians(18))
ok(abs(bc - 3.09) < 0.005, "2502 BC ≈ 3,09")
ok(round(5 - 3.09, 2) == 1.91 and abs((5 - bc) - 1.91) < 0.005, "2502 DC")

# ------------------------------------------------------------------ 2503
ok([t * t - 1 for t in (3, 5, 7, 9)] == [8, 24, 48, 80] and all((t * t - 1) % 8 == 0 for t in (3, 5, 7, 9)), "2503 Q1")
ident((2 * n + 1) ** 2 - 1, 4 * n * (n + 1), "2503 Q3")
ok(all(((2 * t + 1) ** 2 - 1) % 8 == 0 for t in range(500)), "2503 Q4 contrôle numérique")
ident((2 * n) ** 2 - 1, 2 * (2 * n ** 2 - 1) + 1, "2503 Q5")
ok(10 ** 2 - 1 == 99, "2503 Q5 essai")

# ------------------------------------------------------------------ 2504
ident((2 * n + 1) + (2 * n + 3), 4 * (n + 1), "2504 Q1")
ok(7 + 9 == 16, "2504 Q1 ex")
ok(abs(100 * 1.1 * 0.9 - 99) < 1e-9, "2504 Q2")
ok(25 ** 2 == 625 == 7 ** 2 + 24 ** 2 and 24 ** 2 == 576, "2504 Q3")
ok(F(2, 5) != F(3, 6) and 2 * 6 == 12 and 3 * 5 == 15 and F(2, 5) * 6 == F(24, 10), "2504 Q4")
ident((n + 1) ** 2 - n ** 2, 2 * n + 1, "2504 Q5")
ok(36 - 25 == 11, "2504 Q5 ex")

# ------------------------------------------------------------------ 2505
ok(15 ** 2 == 225 == 9 ** 2 + 12 ** 2, "2505 Q1")
ok(F(6, 9) == F(10, 15) == F(2, 3), "2505 Q2")
ok(F(2, 3) * 12 == 8 and 6 * 8 / 2 == 24, "2505 Q4")
ok(F(9, 15) == F(3, 5) != F(2, 3) and F(2, 3) == F(10, 15), "2505 Q5")

print(f"{OK} contrôles OK")
