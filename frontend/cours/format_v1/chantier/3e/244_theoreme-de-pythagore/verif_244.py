"""Vérification (sympy) de tous les résultats numériques de la notion 244 (cours, fiche, exercices)."""
from sympy import Rational as R, sqrt, nsimplify, symbols, expand

ok = 0


def v(nom, a, b):
    global ok
    a, b = nsimplify(a), nsimplify(b)
    assert a == b, f"{nom} : {a} != {b}"
    ok += 1


def vf(nom, a, b, tol=0.005):
    global ok
    assert abs(float(a) - float(b)) < tol, f"{nom} : {float(a)} vs {b}"
    ok += 1


def arr(x, n):
    """arrondi décimal à n chiffres, comme une calculatrice"""
    return round(float(x) + 1e-12, n)


