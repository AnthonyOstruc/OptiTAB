"""Vérification sympy de toutes les valeurs numériques de la notion 287 (cosinus, 4e).

Chaque contrôle compare la valeur exacte (sympy) au résultat écrit dans le cours,
la fiche ou un corrigé, avec la tolérance de l'arrondi annoncé. Les arrondis
« au dixième », « au centième »… sont contrôlés par round_ok (arrondi au plus proche).
"""
from sympy import Rational as R, sqrt, cos, acos, pi, N, nsimplify

deg = pi / 180
ok = 0


def chk(nom, val, attendu, tol):
    global ok
    v = float(N(val, 30))
    assert abs(v - attendu) <= tol, (nom, v, attendu)
    ok += 1
    print("OK %-46s %.6f ~ %s" % (nom, v, attendu))


def arr(nom, val, attendu, chiffres):
    """La valeur arrondie à `chiffres` décimales vaut exactement `attendu`."""
    global ok
    v = float(N(val, 30))
    assert round(v + 1e-12, chiffres) == round(attendu, chiffres), (nom, v, attendu)
    ok += 1
    print("OK %-46s %.6f -> %s" % (nom, v, attendu))


