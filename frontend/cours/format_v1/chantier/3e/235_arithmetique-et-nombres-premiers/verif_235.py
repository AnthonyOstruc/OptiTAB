from fractions import Fraction as Fr
from math import gcd, lcm, isqrt
from sympy import factorint, isprime, divisors, primerange

n_ok = 0


def ok(cond, msg):
    global n_ok
    assert cond, msg
    n_ok += 1


def fac(n, d):
    ok(factorint(n) == d, f"décomposition de {n}: {factorint(n)}")


