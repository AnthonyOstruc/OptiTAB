# -*- coding: utf-8 -*-
"""Contrôles numériques du chapitre 7 (proportionnalité et pourcentages) — 4ème."""
from fractions import Fraction as F
from math import pi

D = lambda s: F(s)  # noqa: E731
r = lambda v, n=2: round(float(v) + 1e-12, n)  # noqa: E731

# Cours / fiche
assert F(7, 2) == D('17.5') / 5 == F(28, 8) == D('3.5') and 9 * D('9.60') / 6 == D('14.40')
assert D('0.15') * 240 == 36 and F(21, 28) == D('0.75') and 60 * D('0.7') == 42 and 250 * D('1.08') == 270
assert 100 * D('1.1') * D('0.9') == 99 and 68 / D('0.85') == 80 and 4 * 25000 == 100000

# D1
assert F(86, 2) != F(116, 6) and F(6, D('1.5')) == F(16, 4) == F(28, 7) == 4 and 1 != F(9, 3)
assert 12 * D('3.5') == 42 and 49 / D('3.5') == 14
# D2
assert D('9.60') / 6 == D('1.60') and 15 * D('1.6') == 24 and 40 / D('1.6') == 25
assert D('9.60') + D('14.40') == 24 and D('9.60') / 2 == D('4.80')
# D3
assert D('0.2') * 80 == 16 and D('0.075') * 1200 == 90 and F(18, 72) == D('0.25') and D('1.2') * 50 == 60
# D4
assert 4 * D('2.4') == D('9.6') and F(12, 5) == D('2.4') and 18 / D('2.4') == D('7.5')
g2 = lambda m: D('1.5') * m + 6  # noqa: E731
g3 = lambda m: D('0.35') * m * m  # noqa: E731
assert g2(2) == 9 and g2(4) == 12 and F(9, 2) != F(12, 4) and g3(2) == D('1.4') and g3(4) == D('5.6')
# D5
assert D('0.3') * 60 == 18 and 1 - D('0.4') == D('0.6')
# D6
assert 3 * 200 == 600 and F(450, 200) == D('2.25') and F(350000, 25000) == 14 and F(6, 1200) == F(1, 200)
assert F(430, 43) == 10
# D7
assert 90 * F(7, 3) == 210 and F(270, 90) == 3 and 90 * F(5, 3) == 150

# E1
assert 40 * D('1.85') == 74 and r(50 / 1.85) == 27.03 and 55 * D('1.85') == D('101.75')
assert D('101.75') * D('0.95') == D('96.6625') and r((1.92 - 1.85) / 1.85 * 100, 1) == 3.8
# E2
aires = [D('6.2') * D('4.5'), D('4.2') * D('3.5'), D('4.2') * D('2.7'), D('6.2') * D('1.7')]
assert aires == [D('27.9'), D('14.7'), D('11.34'), D('10.54')]
assert sum(aires) == D('64.48') == D('10.4') * D('6.2') and D('6.2') + D('4.2') == D('10.4')
assert D('4.5') + D('1.7') == D('6.2') and F(620, 50) == D('12.4') and D('6.2') - D('3.5') == D('2.7')
# E3
assert D('2.10') / 3 == D('0.70') and D('5.20') / 8 == D('0.65') and 3 * D('2.10') * D('0.8') == D('5.04')
assert 2 * D('2.10') == D('4.20') and r(2.10 / 6.30 * 100, 1) == 33.3 and D('5.20') + D('2.10') == D('7.30')
# E4
assert 8 * D('0.4') == D('3.2') and 72 * D('0.4') == D('28.8') and 24 * D('0.4') == D('9.6')
assert 3 * D('0.4') == D('1.2') and D('9.6') / 50 == D('0.192')
# E5
assert 1800 * D('1.05') == 1890 and 1890 * D('1.03') == D('1946.70') and D('1.05') * D('1.03') == D('1.0815')
assert 50 * D('0.8') * D('1.2') == 48 and D('0.8') * D('1.2') == D('0.96') and 1 / D('0.8') == D('1.25')
# E6
assert 150 * D('1.2') == 180 and 96 / D('1.2') == 80 and 20 * D('1.055') == D('21.10')
assert D('31.65') / D('1.055') == 30 and 96 * D('0.8') == D('76.8')
# E7
assert [r(pi * d) for d in (1, 2, 5, 10)] == [3.14, 6.28, 15.71, 31.42]

# P1
assert D('7.8') * D('6.5') == D('50.7') and r(50.7 * 1.85) == 93.8 and round(45 / 6.5 * 100) == 692
assert 600 * D('0.09') == 54 and D('93.80') + 54 == D('147.80') and D('147.80') / 4 == D('36.95')
assert D('6.5') * D('0.88') == D('5.72') and D('7.8') * D('5.72') == D('44.616')
assert D('50.7') - D('44.616') == D('6.084') and r(6.084 * 1.85) == 11.26
# P2
assert 180 * D('0.7') == 126 and 126 * D('0.8') == D('100.80') and 180 - D('100.80') == D('79.20')
assert D('79.20') / 180 == D('0.44') and D('0.7') * D('0.8') == D('0.56') and 180 * D('0.55') == 99
assert 70 / D('0.56') == 125 and 125 * D('0.7') == D('87.5') and D('87.5') * D('0.8') == 70
# P3
assert 18 * 25000 == 450000 and D('4.5') / 4 == D('1.125') and D('0.125') * 60 == D('7.5')
assert F(450, 300) == D('1.5') and 11 * 25000 == 275000 and D('4.5') - D('2.75') == D('1.75')
# 9 h 15 + 2 h 37 min 30 s = 11 h 52 min 30 s
assert (9 * 3600 + 15 * 60) + (2 * 3600 + 37 * 60 + 30) == 11 * 3600 + 52 * 60 + 30
# P4
assert 12500 * D('1.04') == 13000 and 13000 * D('1.04') == 13520 and D('1.04') ** 2 == D('1.0816')
assert D('0.15') * 13520 == 2028 and r(1800 / 2028 * 100, 1) == 88.8
assert 12500 * D('0.96') ** 2 == 11520 and D('0.96') ** 2 == D('0.9216')
# P5
assert D('0.3') + D('0.8') * D('0.5') == D('0.7') and r(0.7 / 1.5 * 100, 1) == 46.7
xx = F(2, 10) / F(3, 10)
assert xx == F(2, 3) and (D('0.3') + D('0.8') * xx) / (1 + xx) == F(1, 2)
# P6
assert 25 * D('1.5') == D('37.5') and D('937.5') / 150 == D('6.25') == D('2.5') ** 2
assert F(13, 10) != F(18, 15) and 15 * D('1.3') == D('19.5') and D('19.5') - 18 == D('1.5')
# P7
assert F(85, 2) == D('42.5') and F(120, 3) == 40 and F(210, 6) == 35 and 270 - 210 == 60
assert r(60 / 270 * 100, 1) == 22.2 and 4 * 210 * D('0.9') == 756 and 210 * D('1.04') == D('218.40')

print("check_ch07 : tous les contrôles passent.")
