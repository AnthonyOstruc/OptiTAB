"""Vérification sympy de tous les calculs de la notion 257 (4e) : cours, fiche, exercices."""
from sympy import Rational as R, pi, Symbol, solve, nsimplify, floor, ceiling

n = 0
def ok(cond, msg):
    global n
    assert cond, msg
    n += 1

def eq(a, b, msg):
    ok(nsimplify(a) == nsimplify(b), f"{msg} : {a} != {b}")

def arr(x, d):
    """arrondi décimal à d chiffres (demi vers le haut)"""
    return floor(nsimplify(x) * 10**d + R(1, 2)) / R(10**d)

