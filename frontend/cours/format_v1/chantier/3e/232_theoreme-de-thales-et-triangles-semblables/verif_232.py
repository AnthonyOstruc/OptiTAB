v("2232 Pyth AMN", R("4.5") ** 2 + 6 ** 2, R("7.5") ** 2); v("2232 Pyth ABC", 6 ** 2 + 8 ** 2, 10 ** 2)
v("2232 aires", (R("4.5") * 6 / 2) / (6 * 8 / 2), R("0.75") ** 2); v("2232 A1", R("4.5") * 6 / 2, R("13.5"))
# figure 2232 : coordonnées cohérentes (A(0;6), M(0;1,5), N(6;1,5), C(8;0))
v("2232 fig AN", sqrt(6 ** 2 + R("4.5") ** 2), R("7.5")); v("2232 fig AC", sqrt(8 ** 2 + 6 ** 2), 10)
print(f"{ok} contrôles OK")
