ok = 0


def v(nom, a, b):
    """égalité exacte"""
    global ok
    a, b = nsimplify(a), nsimplify(b)
    assert a == b, f"{nom} : {a} != {b}"
    ok += 1


def arr(x, n):
    """arrondi décimal à n chiffres, comme une calculatrice"""
    return round(float(x) + 1e-12, n)


def va(nom, x, n, attendu):
    """arrondi à n décimales"""
    global ok
    assert arr(x, n) == attendu, f"{nom} : {float(x)} arrondi à {n} = {arr(x, n)} != {attendu}"
    ok += 1


def vrai(nom, cond):
    global ok
    assert cond, nom
    ok += 1


