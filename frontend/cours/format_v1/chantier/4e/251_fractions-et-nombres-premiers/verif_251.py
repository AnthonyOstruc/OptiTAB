n_ok = 0


def ok(cond, msg):
    global n_ok
    assert cond, msg
    n_ok += 1


def fac(n, d):
    ok(factorint(n) == d, f"décomposition de {n} : {factorint(n)}")


def div_par(n):
    """Critères de divisibilité (2, 3, 4, 5, 9, 10) comparés à la vraie divisibilité."""
    s = sum(map(int, str(n)))
    crit = {2: int(str(n)[-1]) % 2 == 0, 3: s % 3 == 0, 4: int(str(n)[-2:]) % 4 == 0,
            5: str(n)[-1] in "05", 9: s % 9 == 0, 10: str(n)[-1] == "0"}
    for d, c in crit.items():
        ok(c == (n % d == 0), f"critère {d} pour {n}")
    return {d for d, c in crit.items() if c}


