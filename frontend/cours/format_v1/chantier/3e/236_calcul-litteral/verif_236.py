# -*- coding: utf-8 -*-
"""Vérification des calculs de la notion 236 (cours, fiche, exercices) avec sympy."""
from sympy import symbols, expand, factor, Rational, solve, simplify

x, n, a, b, c, d, k = symbols("x n a b c d k")
n_ok = 0


def ok(cond, msg):
    global n_ok
    assert cond, msg
    n_ok += 1


def eg(e1, e2, msg):
    ok(simplify(expand(e1) - expand(e2)) == 0, msg)


def val(e, v):
    return e.subs(x, v)


# ---------------- cours / fiche
ok(val(3*x**2 - 5*x, -2) == 22, "cours substitution")
eg(7*x - 4 + 3*x**2 + 9 - 2*x, 3*x**2 + 5*x + 5, "cours réduire")
eg(k*(a + b), k*a + k*b, "k(a+b)"); eg(k*(a - b), k*a - k*b, "k(a-b)")
eg(5*(2*x - 3), 10*x - 15, "5(2x-3)"); eg(-(4*x - 7), -4*x + 7, "-(4x-7)")
eg((a + b)*(c + d), a*c + a*d + b*c + b*d, "double distrib")
eg((2*x - 3)*(x + 4), 2*x**2 + 5*x - 12, "(2x-3)(x+4)")
eg(3*x*(2*x - 3), 6*x**2 - 9*x, "6x²-9x"); eg((x - 2)*(3*x + 5), 3*x*(x - 2) + 5*(x - 2), "facteur parenthèse")
eg((a + b)**2, a**2 + 2*a*b + b**2, "id1"); eg((a - b)**2, a**2 - 2*a*b + b**2, "id2"); eg((a + b)*(a - b), a**2 - b**2, "id3")
eg((x + 6)**2, x**2 + 12*x + 36, "(x+6)²"); eg((2*x - 3)**2, 4*x**2 - 12*x + 9, "(2x-3)²")
eg((2*x - 5)*(2*x + 5), 4*x**2 - 25, "4x²-25")
ok(103*97 == 9991 and 99**2 == 9801 and (3 + 4)**2 == 49 and 3**2 + 4**2 == 25, "calculs astucieux cours")
eg(3*(x + 4) - 3*x, 12, "programme cours")
eg((2*n + 1)**2, 2*(2*n**2 + 2*n) + 1, "impair au carré")
eg(3*x + 2*x - 1, 5*x - 1, "fiche réduire"); eg(x**2 - 81, (x - 9)*(x + 9), "fiche x²-81")
eg(5*x + 5, 5*(x + 1), "5x+5"); ok(expand(-2*(x - 3)) == -2*x + 6, "fiche -2(x-3)")

# ---------------- 2160
A = 2*x**2 - 3*x + 1; B = 5*x - x**2
ok([val(A, -2), val(A, 3), val(A, 0), val(B, -1), val(B, 2)] == [15, 10, 1, -6, 6], "2160")
# ---------------- 2197
eg(7*x - 4 + 3*x + 9 - 2*x, 8*x + 5, "2197 q1"); eg(5*x + 3 - x - 8, 4*x - 5, "2197 q2")
eg(2*x**2 + 3*x - x**2 + x, x**2 + 4*x, "2197 q3"); eg(4 - 2*x + 7*x - 9, 5*x - 5, "2197 q4")
ok(val(8*x + 5, 2) == 21 and val(13*x, 2) == 26 and val(8*x + 5, 1) == 13, "2197 q5")
# ---------------- 2162
C = -(4*x - 7) + 2*(3 - x)
eg(C, -6*x + 13, "2162 C"); eg(-(-2*x + 5), 2*x - 5, "2162 q4")
ok(val(C, 0) == 13 and val(C, 1) == 7, "2162 q5")
# ---------------- 2163
eg((3*x + 2)*(x - 5), 3*x**2 - 13*x - 10, "2163 q1"); eg((x + 4)*(x + 2), x**2 + 6*x + 8, "2163 q2")
eg((2*x - 1)*(x + 3), 2*x**2 + 5*x - 3, "2163 q3"); ok(val((2*x - 1)*(x + 3), 1) == 4, "2163 q4")
# ---------------- 2164
eg(14*x + 21, 7*(2*x + 3), "2164 q1"); eg(12*x**2 - 8*x, 4*x*(3*x - 2), "2164 q2")
eg(5*x + 5, 5*(x + 1), "2164 q3"); eg(x**2 + 7*x, x*(x + 7), "2164 q4")
# ---------------- 2165 / 2166
eg(5*(2*x - 3), 10*x - 15, "2165 q5")
eg(4*(3*x + 7), 12*x + 28, "2166 q1"); eg(-2*(5*x - 3), -10*x + 6, "2166 q2"); eg(x*(x + 6), x**2 + 6*x, "2166 q3")
eg(3*x*(2*x - 5), 6*x**2 - 15*x, "2166 q4"); eg(-(x**2 - 4*x + 1), -x**2 + 4*x - 1, "2166 q5")
# ---------------- 2167
eg(x**2 - 81, (x - 9)*(x + 9), "2167 q1"); eg(25*x**2 - 4, (5*x - 2)*(5*x + 2), "2167 q2")
eg(49 - x**2, (7 - x)*(7 + x), "2167 q3"); eg(36*x**2 - 1, (6*x - 1)*(6*x + 1), "2167 q4")
# ---------------- 2198
eg((x + 6)**2, x**2 + 12*x + 36, "2198 q1"); eg((2*x - 3)**2, 4*x**2 - 12*x + 9, "2198 q2")
eg((3*x + 1)**2, 9*x**2 + 6*x + 1, "2198 q3"); ok(val((x + 6)**2, 1) == 49 and val(x**2 + 36, 1) == 37, "2198 q4")
# ---------------- 2169
ok(103*97 == 9991 and 49**2 == 2401 and 101**2 == 10201 and 1002*998 == 999996 and 55**2 - 45**2 == 1000, "2169")
# ---------------- 2170
eg(3*x*(x - 2) + 5*(x - 2), (x - 2)*(3*x + 5), "2170 q1"); eg((x - 2)*(3*x + 5), 3*x**2 - x - 10, "2170 q1 dev")
eg(9*x**2 - 36, 9*(x - 2)*(x + 2), "2170 q2"); eg((x + 1)*(2*x - 3) + (x + 1)*(x + 7), (x + 1)*(3*x + 4), "2170 q3")
eg(2*x**2 - 50, 2*(x - 5)*(x + 5), "2170 q4")
# ---------------- 2199
R = (2*x + 3)*(x + 5)
eg(R, 2*x**2 + 3*x + 10*x + 15, "2199 aires"); eg(R, 2*x**2 + 13*x + 15, "2199 q3")
ok(val(R, 4) == 99 and 11*9 == 99 and 32 + 52 + 15 == 99, "2199 q4")
# ---------------- 2172
eg((2*x + 1)*(3*x - 4), 6*x**2 - 5*x - 4, "2172 q1")
E = (2*x + 1)*(3*x - 4) - 6*x**2
eg(E, -5*x - 4, "2172 q2"); ok(val(E, 10) == -54 and 21*26 == 546 and val(E, -2) == 6, "2172 q3 q4")
# ---------------- 2173
eg(8*x + 12, 4*(2*x + 3), "2173 q1"); eg(25 - x**2, (5 - x)*(5 + x), "2173 q2"); eg(3*x**2 - 27, 3*(x - 3)*(x + 3), "2173 q3")
eg(x**2 + 10*x + 25, (x + 5)**2, "2173 q4"); eg(x**2 - 12*x + 36, (x - 6)**2, "2173 q5")
ok(expand((x + 6)**2) != x**2 + 10*x + 36, "2173 attention")
# ---------------- 2174
PA = 4*(x + 5) - 8; PB = 4*x + 12
ok(val(PA, 3) == val(PB, 3) == 24 and val(PA, -5) == val(PB, -5) == -8, "2174 q1")
eg(PA, PB, "2174 q4"); ok(solve(PB - 100, x) == [22], "2174 q5")
# ---------------- 2175
eg((x + 4)**2 - x**2, 8*x + 16, "2175 q2"); eg(4*2*x + 4*2**2, 8*x + 16, "2175 q3")
ok(val(8*x + 16, 7) == 72 and 11**2 - 7**2 == 72, "2175 q4"); ok(solve(8*x + 16 - 56, x) == [5] and 9**2 - 5**2 == 56, "2175 q5")
# ---------------- 2176
eg((2*n + 1)**2, 2*(2*n**2 + 2*n) + 1, "2176 q3"); eg((2*n)**2, 4*n**2, "2176 q4")
ok(all((m*(m + 1)) % 2 == 0 for m in range(-50, 50)), "2176 q5 (contrôle numérique)")
# ---------------- 2177
eg((x + 3)**2 - x**2, 6*x + 9, "2177 q1")
ok(solve(6*x + 9 - 9, x) == [0] and solve(6*x + 9 - 39, x) == [5] and 64 - 25 == 39, "2177 q2 q3")
ok(solve(6*x + 9 - 100, x) == [Rational(91, 6)] and abs(91/6 - 15.17) < 0.01, "2177 q4")
# ---------------- 2178
Aa = (x + 1)**2; Bb = x*(x + 2)
ok(val(Aa, 5) == 36 and val(Bb, 5) == 35 and val(Aa, -3) == 4 and val(Bb, -3) == 3, "2178 q1")
eg(Aa - Bb, 1, "2178 q3"); ok(1001**2 - 1000*1002 == 1, "2178 q4")
# ---------------- 2179
F = (x - 2)*(x + 5) + 3*(x - 2)
eg(F, x**2 + 6*x - 16, "2179 q1"); eg(F, (x - 2)*(x + 8), "2179 q2")
ok(val(F, 0) == -16 and val(F, 2) == 0 and sorted(solve(F, x)) == [-8, 2], "2179 q3 q4")
# ---------------- 2200
eg(n + (n + 1) + (n + 2), 3*(n + 1), "2200 q2"); ok(4 + 5 + 6 == 15 and 11 + 12 + 13 == 36, "2200 q1")
eg(n + (n + 1), 2*n + 1, "2200 q4"); eg(sum(n + i for i in range(5)), 5*(n + 2), "2200 q5")

print(f"verif_236 : {n_ok} contrôles, tout est juste.")
