from sympy import Rational as R, sqrt, pi, nsimplify, Symbol, solve, acos, deg, Integer, N

ok = 0
d = R


def v(nom, a, b):
    """égalité exacte"""
    global ok
    a, b = nsimplify(a), nsimplify(b)
    assert (a - b).simplify() == 0, f"{nom} : {a} != {b}"
    ok += 1


def arr(x, n):
    return round(float(N(x, 30)) + 1e-12, n)


def va(nom, x, n, attendu):
    """arrondi à n décimales"""
    global ok
    assert arr(x, n) == attendu, f"{nom} : {float(N(x))} arrondi à {n} = {arr(x, n)} != {attendu}"
    ok += 1


def vrai(nom, cond):
    global ok
    assert cond, nom
    ok += 1


def pyr(B, h):
    return B * h / 3


def cone(r, h):
    return pi * r ** 2 * h / 3


def angle(c):
    return deg(acos(c))


