"""Vérification sympy de tous les calculs de la notion 258 (4e : grandeurs composées et unités).

Lancer : python verif_258.py  -> affiche le nombre de contrôles et s'arrête à la première erreur.
"""
from sympy import Rational as R, Integer as I, floor, sympify

N = 0


def ok(nom, valeur, attendu, tol=None):
    """valeur exacte == attendu, ou |valeur - attendu| <= tol (arrondis)."""
    global N
    if isinstance(attendu, tuple):
        assert tuple(sympify(x) for x in valeur) == tuple(sympify(x) for x in attendu), f"{nom} : {valeur} != {attendu}"
    elif tol is None:
        assert sympify(valeur) == sympify(attendu), f"{nom} : {valeur} != {attendu}"
    else:
        assert abs(float(valeur) - float(attendu)) <= tol, f"{nom} : {float(valeur)} vs {attendu}"
    N += 1


def arr(x, n):
    """arrondi de x à n décimales (demi vers le haut)."""
    return floor(x * 10**n + R(1, 2)) / I(10)**n


def hmin(h):
    """heures décimales -> (heures, minutes exactes)."""
    hh = floor(h)
    return hh, (h - hh) * 60


