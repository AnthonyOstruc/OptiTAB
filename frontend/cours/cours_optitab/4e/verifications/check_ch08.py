# -*- coding: utf-8 -*-
"""Contrôles numériques du chapitre 8 (grandeurs composées et unités) — 4ème."""
from fractions import Fraction as F
from math import pi

D = lambda s: F(s)  # noqa: E731
r = lambda v, n=2: round(float(v) + 1e-12, n)  # noqa: E731

# Cours / fiche
assert D('0.4') * 60 == 24 and F(45, 60) == D('0.75') and F(20, 60) == F(1, 3)
assert F(150, 2) == 75 and 80 * D('2.5') == 200 and F(300, 120) == D('2.5') and 90 / D('3.6') == 25
assert F(60, D('2.5')) == 24 and F(150, 12) == D('12.5') and 2 * D('1.5') == 3

# D1
assert [D(x) * 60 for x in ('0.5', '0.25', '0.1')] == [30, 15, 6] and D('0.75') * 60 == 45
assert 1 + F(12, 60) == D('1.2') and 3 + F(1, 3) == F(10, 3) and r(10 / 3) == 3.33
assert (2 * 60 + 45) + (60 + 35) == 4 * 60 + 20
# D2
assert F(36, D('1.5')) == 24 and 10 / F(50, 60) == 12 and F(5, 10) * 60 == 30
assert F(100, 10) * D('3.6') == 36 and 72 / D('3.6') == 20
# D3
assert 4 * D('0.75') == 3 and F(21, 14) == D('1.5') and 340 * 3 == 1020 and r(1000 / 340) == 2.94
# D4
assert r(50 / 3.6, 1) == 13.9 and 30 * D('3.6') == 108 and D('1.2') * 60 == 72
assert 72 / D('3.6') == 20 and r(80 / 3.6, 1) == 22.2
# D5
assert D('2.5') * 1000 == 2500 and 60 * 30 * 40 == 72000 and 3000 / D('1.5') == 2000
# D6
assert 12 * 5 == 60 and 12 * 60 == 720 and 24 * 3600 == 86400 and F(86400, 20) == 4320
assert D('4.32') * 365 == D('1576.8') and r(1.5768 * 4) == 6.31
# D7
assert F(7800, 1000) == D('7.8') and F(2700, 1000) == D('2.7') and F(600, 1000) == D('0.6')
assert D('7.8') * 250 == 1950

# E1
assert F(60, 1) == 60 and F(90, D('1.5')) == 60 and F(150, 3) == 50 and F(150, D('2.5')) == 60
# E2
assert F(30, 20) == D('1.5') and F(60, D('2.5')) == 24 and F(20 + 30, 2) == 25 and F(30, D('0.5')) == 60
# E3
t = 2 * 3600 + 60 + 9
assert t == 7269 and r(42195 / t) == 5.80 and r(42195 / t * 3.6, 1) == 20.9
assert round(t / 42.195) == 172 and 172 == 2 * 60 + 52
assert r(0.2195 * 60) == 13.17 and r(0.17 * 60, 1) == 10.2 and r(10 * t / 3600) == 20.19
assert r(42.195 / 12, 3) == 3.516 and round(0.51625 * 60) == 31
# E4
assert 80 * 35 * 45 == 126000 and 80 * 35 * 40 == 112000 and 112 // 8 == 14
assert 3 * 112 == 336 and D(336) / 60 == D('5.6') and 80 * 35 == 2800
# E5
assert D('0.01') * 6 == D('0.06') and D('0.06') * 30 == D('1.8') and D('0.12') * 4 * 30 == D('14.4')
assert 8 * 3 + D('1.8') + D('14.4') == D('40.2') and D('40.2') * D('0.25') == D('10.05')
assert D('1.5') * 6 * 30 == 270 and 270 * D('0.25') == D('67.5')
# E6
assert 300 * 3600 == 1080000 and 1080000 * 24 == 25920000 and r(2500 / 300) == 8.33
assert r(1700 / 300) == 5.67 and r(2500 / 1700) == 1.47
# E7
assert D('3.90') / D('0.75') == D('5.20') and D('5.88') / D('1.2') == D('4.90') and D('2.16') / D('0.4') == D('5.40')
assert D('3.90') + D('1.95') == D('5.85') and D('5.85') / D('1.5') == D('3.90')

# P1
assert r(60 / 7, 3) == 8.571 and round(0.571 * 60) == 34 and F(60, 50) == D('1.2')
assert 60 * D('0.25') == 15 and 15 * D('0.25') == D('3.75') and D('6.5') * D('1.85') == D('12.025')
assert 150 * (D('12.025') - D('3.75')) == D('1241.25') and 150 * (D('12.03') - D('3.75')) == 1242
# P2
assert 340 * 6 == 2040 and 2040 - 1020 == 1020 and F(1020, 5) == 204 and 204 * 60 == 12240
# P3
assert r(100 / 9.58) == 10.44 and r(100 / 9.58 * 3.6) == 37.58
assert r(200 / 19.19) == 10.42 and r(200 / 19.19 * 3.6) == 37.52 and D('12.4') * D('3.6') == D('44.64')
assert r(100 / 12.4) == 8.06 and round(50 / 3.6 * 9.58) == 133
# P4
assert 180 // 15 == 12 and 180 // 9 == 20 and 9 * 8 == 72 and 180 // 6 == 30
assert 8 * 7 == 56 and 124 * 365 == 45260 and D('45.26') * 4 == D('181.04')
# P5
assert 10 * 4 * D('1.5') == 60 and 60000 // 20 == 3000 and 3000 // 60 == 50 and 60 * 4 == 240
assert 10 * 4 * D('0.004') == D('0.16') and D('0.16') * 30 == D('4.8') and F(50, 40) == D('1.25')
# P6
assert 1000000 * D('0.92') == 920000 and round(1000 / 0.92) == 1087 and r(1 / 0.92 - 1, 3) == 0.087
assert r(0.92 / 1.025 * 100, 1) == 89.8 and round(10000 / (1 - 0.92 / 1.025), -3) == 98000
# P7
L = 2 * pi * 1.5e8
assert r(L / 1e8) == 9.42 and D('365.25') * 24 == 8766 and round(L / 8766, -3) == 108000
assert r(L / 8766 / 3600, 1) == 29.9 and round(40000 / 24) == 1667 and r(107500 / 1667, 1) == 64.5

print("check_ch08 : tous les contrôles passent.")
