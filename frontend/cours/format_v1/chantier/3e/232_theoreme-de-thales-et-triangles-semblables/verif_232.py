# -*- coding: utf-8 -*-
"""Vérification (sympy) de tous les résultats numériques de la notion 232 (cours, fiche, exercices)."""
from sympy import Rational as R, sqrt, symbols, solve, Eq, nsimplify

ok = 0


def v(nom, a, b):
    global ok
    a, b = nsimplify(a), nsimplify(b)
    assert a == b, f"{nom} : {a} != {b}"
    ok += 1


def vf(nom, a, b, tol=R(1, 20)):
    global ok
    assert abs(float(a) - float(b)) < tol, f"{nom} : {float(a)} vs {b}"
    ok += 1


x = symbols("x", positive=True)
# --- cours
v("cours AN emboîtée", R(3, 5) * 7, R("4.2"))
v("cours AN papillon", R(2, 6) * 9, 3)
