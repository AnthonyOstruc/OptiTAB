# -*- coding: utf-8 -*-
"""Vérification des calculs de la notion 255 (4e : calcul littéral et distributivité).

Chaque développement, factorisation, valeur numérique et programme de calcul du
cours, de la fiche et des 21 exercices est recalculé avec sympy (fractions exactes).
"""
from fractions import Fraction as Fr

from sympy import Poly, Rational, expand, factor, simplify, symbols

x, y, a, b, c, d, k, n = symbols("x y a b c d k n")
N = 0


def ok(cond, msg):
    global N
    assert cond, "ÉCHEC : " + msg
    N += 1


def eg(e1, e2, msg):
    ok(simplify(expand(e1) - expand(e2)) == 0, msg)


def neq(e1, e2, v, msg, var=x):
    """e1 et e2 différents pour var = v (contre-exemple)."""
    ok(e1.subs(var, v) != e2.subs(var, v), msg)


def val(e, v, var=x):
    return e.subs(var, v)


R = Rational

# ====================================================================== cours
ok(val(5*x**2 - 3*x + 1, -2) == 27, "cours E(-2)")
ok((-2)**2 == 4 and -2**2 == -4, "cours (-2)^2")
eg(6*x - 4 + 2*x**2 - 9*x + 7, 2*x**2 - 3*x + 3, "cours réduire A")
eg(4*x*5*x, 20*x**2, "cours 4x*5x")
eg(k*(a + b), k*a + k*b, "k(a+b)"); eg(k*(a - b), k*a - k*b, "k(a-b)")
eg(4*(3*x - 2), 12*x - 8, "cours 4(3x-2)"); eg(x*(2*x + 7), 2*x**2 + 7*x, "cours x(2x+7)")
eg(-3*(2*x - 5), -6*x + 15, "cours -3(2x-5)")
eg(9 - (4*x - 1) + 2*(x + 3), -2*x + 16, "cours B")
eg(3*(x + 5), 3*x + 15, "cours 3(x+5)"); eg(-2*(x - 4), -2*x + 8, "cours -2(x-4)")
eg(6*x + 21, 3*(2*x + 7), "cours 6x+21"); eg(5*x**2 - 4*x, x*(5*x - 4), "cours 5x²-4x")
eg(8*x + 8, 8*(x + 1), "cours 8x+8")
eg(18*x - 24, 2*(9*x - 12), "cours 18x-24 (2)"); eg(18*x - 24, 6*(3*x - 4), "cours 18x-24 (6)")
ok(Poly(18*x - 24, x).content() == 6, "cours plus grand facteur 6")
eg((a + b)*(c + d), a*c + a*d + b*c + b*d, "double distributivité")
eg((3*x + 2)*(x - 4), 3*x**2 - 10*x - 8, "cours C")
ok(val((3*x + 2)*(x - 4), 1) == -15 and val(3*x**2 - 10*x - 8, 1) == -15, "cours contrôle x=1")
neq((x + 3)*(x + 2), x**2 + 6, 1, "cours (x+3)(x+2) != x²+6")
ok(5 == (-5)*(-1), "cours (-5)(-1)")
eg(2*(x + 7) - 2*x, 14, "cours programme")
ok((1 + 2)**2 == 9 and 1**2 + 4 == 5, "cours contre-exemple (x+2)²")
eg(n + (n + 1), 2*n + 1, "cours consécutifs")
for v in (1, 2):
    ok(val(x**2 + 2, v) == val(3*x, v), "cours x²+2=3x vrai pour %d" % v)
ok(val(x**2 + 2, 0) == 2 and val(3*x, 0) == 0, "cours x²+2=3x faux pour 0")
# fiche (mêmes exemples) + erreurs classiques
eg(x + x, 2*x, "fiche x+x"); eg(3*x + 2*x, 5*x, "fiche 3x+2x")
eg(9 - (4*x - 1), 10 - 4*x, "fiche 9-(4x-1)")
eg(-(4*x - 1), -4*x + 1, "fiche -(4x-1)")
eg((x + 3)*(x + 2), x**2 + 5*x + 6, "fiche (x+3)(x+2)")

# ====================================================================== 2579
eg(2*a*5, 10*a, "2579 q2a"); eg(x*4*x, 4*x**2, "2579 q2b")
eg(x + 3*x, 4*x, "2579 q4")
ok(4*(5 - 2) == 12 and 4*5 - 2 == 18, "2579 q6")

# ====================================================================== 2580
A = 3*x**2 - 2*x + 5
B = (2*x - 1)*(x + 3)
ok(val(A, 2) == 13, "2580 q1"); ok(val(A, -1) == 10, "2580 q2")
ok(val(A, 0) == 5 and val(A, R(1, 2)) == R(19, 4), "2580 q3 (4,75)")
ok(val(B, 2) == 15, "2580 q4"); ok(val(B, -3) == 0, "2580 q5")
ok(val(A, -2) == 21, "2580 q6"); ok(3*4 - 4 + 5 == 13, "2580 q6 erreur de Léo")

# ====================================================================== 2581
eg(3*x + 5*x, 8*x, "2581 q1"); eg(7*a - 2 + 3*a + 9, 10*a + 7, "2581 q2")
eg(4*x**2 + 3*x - x**2 + x, 3*x**2 + 4*x, "2581 q3"); eg(5*y - 8*y + 2, -3*y + 2, "2581 q4")
eg(2*x*3*x, 6*x**2, "2581 q5a"); eg(5*(-4*x), -20*x, "2581 q5b")
ok(5 + 5 == 10 and 5*5 == 25, "2581 q6")

# ====================================================================== 2582
allum = [4 + 3*(m - 1) for m in range(1, 6)]
ok(allum == [4, 7, 10, 13, 16], "2582 q1")
ok(all(3*m + 1 == allum[m - 1] for m in range(1, 6)), "2582 q2")
eg(4 + 3*(n - 1), 3*n + 1, "2582 q3")
ok(3*100 + 1 == 301, "2582 q4"); ok(3*20 + 1 == 61, "2582 q5"); ok(3*33 + 1 == 100, "2582 q6")

# ====================================================================== 2583
eg(3*(x + 4), 3*x + 12, "2583 q1"); eg(5*(2*a - 3), 10*a - 15, "2583 q2")
eg(-2*(x - 6), -2*x + 12, "2583 q3"); eg(x*(x + 5), x**2 + 5*x, "2583 q4")
eg(-(3*x - 7), -3*x + 7, "2583 q5"); eg(4*(2*x + 1) - 3*(x - 2), 5*x + 10, "2583 q6")
ok(val(4*(2*x + 1) - 3*(x - 2), 1) == 15, "2583 q6 contrôle")

# ====================================================================== 2584
eg(5*x + 15, 5*(x + 3), "2584 q1"); eg(12*a - 18, 6*(2*a - 3), "2584 q2")
ok(Poly(12*a - 18, a).content() == 6, "2584 q2 plus grand facteur")
eg(x**2 + 7*x, x*(x + 7), "2584 q3"); eg(3*x**2 - 6*x, 3*x*(x - 2), "2584 q4")
ok(factor(3*x**2 - 6*x) == 3*x*(x - 2) and Poly(3*x**2 - 6*x, x).content() == 3, "2584 q4 factor")
eg(7*y + 7, 7*(y + 1), "2584 q5")

# ====================================================================== 2585
neq((x + 3)**2, x**2 + 9, 1, "2585 q1"); ok(val((x + 3)**2, 1) == 16 and val(x**2 + 9, 1) == 10, "2585 q1 valeurs")
eg(2*(x + 5), 2*x + 10, "2585 q2")
ok(Fr(1, 2)**2 == Fr(1, 4) and Fr(1, 4) < Fr(1, 2), "2585 q3")
ok(val(3*x + 2*x, 1) == val(5*x**2, 1), "2585 q4 x=1 trompeur")
ok(val(3*x + 2*x, 2) == 10 and val(5*x**2, 2) == 20, "2585 q4 x=2")
eg(-(x - 4), -x + 4, "2585 q5"); neq(-(x - 4), -x - 4, 0, "2585 q5 contre-ex")
eg(x*(x + 1) - x, x**2, "2585 q6")

# ====================================================================== 2586
eg((x + 3)*(x + 2), x**2 + 5*x + 6, "2586 q1"); eg((2*x + 1)*(x + 4), 2*x**2 + 9*x + 4, "2586 q2")
eg((x - 3)*(x + 5), x**2 + 2*x - 15, "2586 q3"); eg((2*a - 1)*(3*a - 2), 6*a**2 - 7*a + 2, "2586 q4")
eg((x + 4)**2, x**2 + 8*x + 16, "2586 q5"); ok(val((x + 4)**2, 1) == 25 and val(x**2 + 16, 1) == 17, "2586 q5 erreur")
ok(13*12 == 156 and val(x**2 + 5*x + 6, 10) == 156, "2586 q6")

# ====================================================================== 2587
P = 2*((2*x + 3) + x); Ar = x*(2*x + 3)
eg(P, 6*x + 6, "2587 q1"); eg(Ar, 2*x**2 + 3*x, "2587 q2")
ok(val(P, 4) == 30 and val(Ar, 4) == 44 and 2*(11 + 4) == 30 and 11*4 == 44, "2587 q3")
ok(val(P, 6) == 42, "2587 q4"); ok(val(Ar, 6) == 90 and 15*6 == 90, "2587 q5")
ok(val(Ar, 8) == 152 and 2*44 == 88, "2587 q6")

# ====================================================================== 2588
def progA(v): return (v + 3)*2 - 6
def progB(v): return v*4 - v - v
ok(progA(5) == 10 and progB(5) == 10, "2588 q1"); ok(progA(-2) == -4 and progB(-2) == -4, "2588 q2")
eg(2*(x + 3) - 6, 2*x, "2588 q3"); eg(4*x - x - x, 2*x, "2588 q4")
eg(x*(x + 2) - x**2, 2*x, "2588 q6"); ok(5*7 - 25 == 10, "2588 q6 contrôle")

# ====================================================================== 2589
neq(5*x + 3, 8*x, 0, "2589 q1")
neq(4*(x + 6), 4*x + 6, 0, "2589 q2"); eg(4*(x + 6), 4*x + 24, "2589 q2 corr")
neq(-(2*x - 9), -2*x - 9, 0, "2589 q3"); eg(-(2*x - 9), -2*x + 9, "2589 q3 corr")
ok(val(2*x*4*x, 1) == val(8*x, 1), "2589 q4 x=1 pas un contre-exemple")
ok(val(2*x*4*x, 2) == 32 and val(8*x, 2) == 16, "2589 q4 x=2"); eg(2*x*4*x, 8*x**2, "2589 q4 corr")
ok(val((x + 4)*(x + 1), 1) == 10 and val(x**2 + 4, 1) == 5, "2589 q5"); eg((x + 4)*(x + 1), x**2 + 5*x + 4, "2589 q5 corr")
ok(val(10*x - 15, 0) == -15 and val(5*(2*x + 3), 0) == 15, "2589 q6"); eg(10*x - 15, 5*(2*x - 3), "2589 q6 corr")

# ====================================================================== 2590
eg(5 - (2*x - 3), 8 - 2*x, "2590 A"); eg(3*x - (-x + 4), 4*x - 4, "2590 B")
eg(2*(x - 1) - (x + 5), x - 7, "2590 C"); eg(-3*(2 - x) + 4*x, 7*x - 6, "2590 D")
eg(x*(x - 2) - 2*(x - 2), x**2 - 4*x + 4, "2590 E"); eg((x + 1)*(x - 1) - x**2, -1, "2590 F")
ok(6*4 - 25 == -1, "2590 F contrôle")

# ====================================================================== 2591
eg(2*(3*x + 4), 6*x + 8, "2591 A"); eg((x + 2)*(x + 5), x**2 + 7*x + 10, "2591 B")
eg(3*x*(x + 2), 3*x**2 + 6*x, "2591 C"); eg(5 - 2*(x - 1), 7 - 2*x, "2591 D")
eg((2*x - 1)*(x + 4), 2*x**2 + 7*x - 4, "2591 E")
ok(val(5 - 2*(x - 1), -1) == 9 and val(7 - 2*x, -1) == 9, "2591 D contrôle")
neq(2*(3*x + 4), 6*x + 4, 0, "2591 intrus"); eg(6*x + 4, 2*(3*x + 2), "2591 factorisation intrus"); ok(Poly(6*x + 4, x).content() == 2, "2591 plus grand facteur")
reduites = [6*x + 8, 3*x**2 + 6*x, 7 - 2*x, 2*x**2 + 7*x - 4, x**2 + 7*x + 10, 6*x + 4]
formes = [2*(3*x + 4), (x + 2)*(x + 5), 3*x*(x + 2), 5 - 2*(x - 1), (2*x - 1)*(x + 4)]
ok(sum(1 for r in reduites if any(expand(f - r) == 0 for f in formes)) == 5, "2591 un seul intrus")

# ====================================================================== 2592
ok(7 + 8 + 9 == 24 == 3*8, "2592 q1"); eg(n + (n + 1) + (n + 2), 3*(n + 1), "2592 q2")
ok(11 + 13 == 24 == 4*6, "2592 q3"); eg((2*n + 1) + (2*n + 3), 4*(n + 1), "2592 q4")
ok(4*5 + 5 == 25 == 5**2, "2592 q5"); eg(n*(n + 1) + (n + 1), (n + 1)**2, "2592 q6")
eg((n + 1)**2, n**2 + 2*n + 1, "2592 q6 forme")

# ====================================================================== 2593
G = (2*x + 2)*(x + 2)
eg(G, 2*x**2 + 6*x + 4, "2593 q2"); eg(G - 2*x*x, 6*x + 4, "2593 q3")
ok(val(6*x + 4, 4) == 28 and 10*6 - 8*4 == 28, "2593 q4"); ok(28*45 == 1260, "2593 q5")
ok(val(6*x + 4, 6) == 40 and 14*8 - 12*6 == 40, "2593 q6")
eg(2*x + 2*x + x + x + 4*1, 6*x + 4, "2593 q7 découpage")

# ====================================================================== 2594
CM = [[x - 3, x + 2, x + 1], [x + 4, x, x - 4], [x - 1, x - 2, x + 3]]
lignes = CM + [[CM[i][j] for i in range(3)] for j in range(3)] + \
    [[CM[i][i] for i in range(3)], [CM[i][2 - i] for i in range(3)]]
ok(all(expand(sum(l) - 3*x) == 0 for l in lignes), "2594 q1-3 magique")
ok([[val(e, 5) for e in r] for r in CM] == [[2, 7, 6], [9, 5, 1], [4, 3, 8]], "2594 q4")
ok(sorted(val(e, 5) for r in CM for e in r) == list(range(1, 10)), "2594 q4 de 1 à 9")
ok([[val(e, 10) for e in r] for r in CM] == [[7, 12, 11], [14, 10, 6], [9, 8, 13]], "2594 q5")
ok(sorted(val(e, 10) for r in CM for e in r) == list(range(6, 15)), "2594 q5 de 6 à 14")
ok([[val(e, -2) for e in r] for r in CM] == [[-5, 0, -1], [2, -2, -6], [-3, -4, 1]], "2594 q6")

# ====================================================================== 2595
ok(7**2 - 6**2 == 13 and 10**2 - 9**2 == 19, "2595 q1")
eg((n - 1)**2, n**2 - 2*n + 1, "2595 q2"); ok(val(n**2 - 1, 7, n) == 48 and 6**2 == 36, "2595 q2 erreur")
