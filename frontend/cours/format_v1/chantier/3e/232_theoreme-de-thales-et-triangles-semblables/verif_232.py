v("cours non parallèle", 2 * 7, 14); v("cours 5x3", 5 * 3, 15)
v("cours semblables k", R(6, 4), R("1.5")); v("cours EF", R("1.5") * 5, R("7.5")); v("cours DF", R("1.5") * 6, 9)
v("cours aire k=3", 12 * 3 ** 2, 108)
v("cours ombre", R(9, 1) / R("1.5"), 6)
# --- 2088
v("2088 AN", R(3, 5) * 10, 6); v("2088 MN", R(3, 5) * R("7.5"), R("4.5")); vf("2088 erreur", R(5, 3) * 10, 16.7)
